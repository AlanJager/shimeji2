pub(crate) fn action_type(name: &str) -> Option<PlainType> {
    Some(match name {
        "Embedded" => PlainType::Embedded,
        "Move" => PlainType::Move,
        "Stay" => PlainType::Stay,
        "Animate" => PlainType::Animate,
        "Sequence" => PlainType::Sequence,
        "Select" => PlainType::Select,
        _ => return None,
    })
}
