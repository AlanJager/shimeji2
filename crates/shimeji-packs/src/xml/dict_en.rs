//! English tags. British `Behaviour` spellings are accepted next to `Behavior`.
//! `RegistanceX` / `RegistanceY` are the spellings the reference looks up.

use super::dict::{CanonicalAttr, PlainType, Tag};

pub(crate) fn tag(name: &str) -> Tag {
    match name {
        "Mascot" => Tag::Mascot,
        "Constant" => Tag::Constant,
        "ActionList" => Tag::ActionList,
        "Action" => Tag::Action,
        "ActionReference" => Tag::ActionReference,
        "BehaviorList" | "BehaviourList" => Tag::BehaviorList,
        "Behavior" | "Behaviour" => Tag::Behavior,
        "BehaviorReference" | "BehaviourReference" => Tag::BehaviorReference,
        "NextBehaviorList" | "NextBehaviourList" => Tag::NextBehaviorList,
        "Condition" => Tag::Condition,
        "Animation" => Tag::Animation,
        "Pose" => Tag::Pose,
        "Hotspot" => Tag::Hotspot,
        "Information" => Tag::Information,
        "Name" => Tag::InfoName,
        "PreviewImage" => Tag::PreviewImage,
        "SplashImage" => Tag::SplashImage,
        "Artist" => Tag::Artist,
        "Scripter" => Tag::Scripter,
        "Commissioner" => Tag::Commissioner,
        "Support" => Tag::Support,
        _ => Tag::Other,
    }
}

